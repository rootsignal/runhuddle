const { contextBridge, ipcRenderer } = require("electron");
const invoke = (method, ...args) => ipcRenderer.invoke(method, ...args);
contextBridge.exposeInMainWorld("runhuddle", {
  keyboardShortcuts: () => invoke("keyboard-shortcuts"),
  recordKeyboardShortcuts: (recording) => invoke("record-keyboard-shortcuts", recording),
  saveKeyboardShortcuts: (value) => invoke("save-keyboard-shortcuts", value),
  usage: provider => invoke("usage", provider),
  connectClaudeUsage: enable => invoke("claude-usage-connect", enable),
  editors: () => invoke("editors"),
  chooseEditor: () => invoke("choose-editor"),
  openEditor: (id, target, line) => invoke("open-editor", id, target, line),
  watchGit: (cwd) => invoke("watch-git", cwd),
  createGithubMcpToken: () => invoke("create-github-mcp-token"),
  githubMcpSettings: () => invoke("github-mcp-settings"),
  verifyGithubMcp: () => invoke("verify-github-mcp"),
  saveGithubMcp: (token) => invoke("save-github-mcp", token),
  githubActionsFailure: (cwd, jobURL) => invoke("github-actions-failure", cwd, jobURL),
  githubBranchPR: (cwd, target) => invoke("github-branch-pr", cwd, target),
  gitRepositoryActions: (cwd) => invoke("git-repository-actions", cwd),
  draftGitPullRequest: (cwd, targetRef, agent, source) => invoke("draft-git-pull-request", cwd, targetRef, agent, source),
  cancelGitPullRequestDraft: (cwd, targetRef) => invoke("cancel-git-pull-request-draft", cwd, targetRef),
  prepareGitPullRequest: (cwd, targetRef) => invoke("prepare-git-pull-request", cwd, targetRef),
  openGitPullRequest: (cwd, targetRef, fields) => invoke("open-git-pull-request", cwd, targetRef, fields),
  gitAction: (cwd, action, input) => invoke("git-action", cwd, action, input),
  noteAction: (id, action) => ipcRenderer.invoke("note-action", id, action),
  saveNote: (draft) => invoke("save-note", draft),
  cancelProjectHistoryReview: (folder) => invoke("cancel-project-history-review", folder),
  installedReviewAgents: () => invoke("installed-review-agents"),
  reviewProjectHistory: (folder, agent) => invoke("review-project-history", folder, agent),
  generateRecap: (provider, id, agent) => invoke("generate-recap", provider, id, agent),
  cancelRecap: (provider, id) => invoke("cancel-recap", provider, id),
  history: (provider, id, anchor) => invoke("history", provider, id, anchor),
  searchHistory: (query, folder, scope, refresh) => invoke("history-search", query, folder, scope, refresh),
  cancelHistorySearch: () => invoke("history-search-cancel"),
  openFolder: (cwd, target) => invoke("open-folder", cwd, target),
  gitChanges: (cwd, mode, revision, compareRef) =>
    invoke("git-changes", cwd, mode, revision, compareRef),
  gitTurnCaptures: () => invoke("git-turn-captures"),
  saveGitTurnCapture: (session, capture) => invoke("save-git-turn-capture", session, capture),
  gitTurnCommittedDiffs: (cwd, from, to) => invoke("git-turn-committed-diffs", cwd, from, to),
  gitTurnSnapshot: (cwd) => invoke("git-turn-snapshot", cwd),
  gitDiff: (cwd, file, area, mode, revision, compareRef) =>
    invoke("git-diff", cwd, file, area, mode, revision, compareRef),
  reconnect: () => invoke("reconnect"),
  screenshotPath: (id) => invoke("screenshot-path", id),
  browserState: () => invoke("browser-state"),
  browserLayout: (rect) => invoke("browser-layout", rect),
  navigateBrowser: (url) => invoke("browser-navigate", url),
  browserAction: (action) => invoke("browser-action", action),
  browserAgent: (id) => invoke("browser-agent", id),
  captureBrowser: () => invoke("browser-capture"),
  copyScreenshotPath: (id) => invoke("copy-screenshot-path", id),
  setAppAccent: (accent) => invoke("set-app-accent", accent),
  snapshot: () => invoke("snapshot"),
  reopenBrowserSession: (id) => invoke("reopen-browser-session", id),
  previewProjectFile: (provider, id, file) => invoke("preview-project-file", provider, id, file),
  revealReferencedFile: (provider, id, file) => invoke("reveal-referenced-file", provider, id, file),
  openTerminalLink: (url) => invoke("open-terminal-link", url),
  locateCodexSession: (id) => invoke("locate-codex-session", id),
  viewedTerminal: (id) => invoke("viewed-terminal", id),
  codexPromptReady: (id, terminalId, queued) => invoke("codex-prompt-ready", id, terminalId, queued),
  liveSessionPreview: (provider, id, terminalId) => invoke("live-session-preview", provider, id, terminalId),
  liveSessionFollowUp: (provider, id, terminalId, message, screenshots, queued) =>
    invoke("live-session-follow-up", provider, id, terminalId, message, screenshots, queued),
  screenshotDraft: (id) => invoke("screenshot-draft", id),
  copyInboxReply: (id, text) => invoke("copy-inbox-reply", id, text),
  inboxPreview: (id) => invoke("inbox-preview", id),
  inboxAction: (id, action) => invoke("inbox-action", id, action),
  chooseFolder: () => invoke("choose-folder"),
  create: (cwd, agent, compactShell) => invoke("create", cwd, agent, compactShell),
  pinSession: (provider, id, pinned) => invoke("pin-session", provider, id, pinned),
  setSessionsHidden: (ids, hidden) => invoke("set-history-hidden", "sessions", ids, hidden),
  setHistoryHidden: (kind, id, hidden) => invoke("set-history-hidden", kind, id, hidden),
  recordSessionContinuation: (from, to, title) => invoke("record-session-continuation", from, to, title),
  title: (id, title) => invoke("title", id, title),
  resume: (provider, id) => invoke("resume", provider, id),
  replay: (id) => invoke("replay", id),
  write: (id, data) => invoke("write", id, data),
  resize: (id, cols, rows) => invoke("resize", id, cols, rows),
  close: (id) => invoke("close", id),
  updateTerminalService: () => invoke("update-terminal-service"),
  onEvent: (callback) => {
    const listener = (_, value) => callback(value);
    ipcRenderer.on("event", listener);
    return () => ipcRenderer.removeListener("event", listener);
  },
});
